import java.util.*;
public class for1 {
    public static void main(String args[]){
        Scanner sc=new Scanner(System.in);
        //int i=1;
        int num=sc.nextInt();
        for(int i=1; i<=num;i++)
            {
            for(int j=1;j<=num;j++)
            {
            System.out.print(" *");
            }
            System.out.println();
            }
    }
    
}
