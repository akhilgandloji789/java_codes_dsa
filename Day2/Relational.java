import java.util.*;
public class Relational {
    public static void main(String args[]){
        //relational
        int a=10;
        int b=5;
        System.out.println(a==b);
        System.out.println(a!=b);
        System.out.println(a>b);
        System.out.println(a<b);
        System.out.println(a>=b);
        System.out.println(a<=b);

        System.out.println((3>2) && (5<0));
        System.out.println((3>2) || (5<0));
        System.out.println(5!=6);

        //Assignment operators
        int h=10;
        h+=10;
        System.out.println(h);
        System.out.println();
        System.out.println();
        System.out.println();
        System.out.println();
    }
    
}
