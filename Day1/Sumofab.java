import java.util.*;
public class Sumofab{
    public static void main(String args[]){
        Scanner sc=new Scanner(System.in);
        /* code to calculate sum of a and b
        using scanner class and print the sum of a and b
        */
        int a=sc.nextInt();
        int b=sc.nextInt();
        int sum=a+b;
        System.out.println(sum);
    }
}