import java.util.*;
public class Productofab{
    public static void main(String args[]){
        Scanner sc=new Scanner(System.in);
        /* code to calculate product of a and b
        using scanner class and print the product of a and b
        */  
       int a=sc.nextInt();
       int b=sc.nextInt();
       int product=a*b;
       System.out.println(product);
    }
}